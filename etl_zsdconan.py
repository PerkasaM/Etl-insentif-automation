def _get_target_quarters(target_df: pd.DataFrame) -> pd.DataFrame:
    """Ambil target per cycle dan Q1 per SDO."""
    t = target_df.copy()
    t.columns = [str(c).strip() for c in t.columns]
    t = t.rename(columns={t.columns[0]: "SDO"})
    t["SDO"] = t["SDO"].astype(str).str.strip().str.upper()
    t = t[t["SDO"].notna() & (t["SDO"] != "TOTAL") & (t["SDO"] != "NONE") & (t["SDO"] != "")]
    # Ambil C01–C12 per cycle
    cycle_cols = [c for c in t.columns if c.startswith("C0") and c[1:].isdigit()]
    out = t[["SDO"] + cycle_cols].copy()
    out["Target_Q1"] = out[["C01", "C02", "C03"]].sum(axis=1)
    return out.reset_index(drop=True)


def _filter_sdo_insentif(df_etl: pd.DataFrame) -> pd.DataFrame:
    """Filter hanya SDO yang ada di SDO_INSENTIF_LIST + remarks SALES/RETUR."""
    sdo_set = {s.upper().strip() for s in SDO_INSENTIF_LIST}
    df_etl = df_etl.copy()
    df_etl["SDO"] = df_etl["SDO"].astype(str).str.strip().str.upper()
    mask = df_etl["SDO"].isin(sdo_set) & df_etl["REMARKS"].isin(FILTER_REMARKS)
    return df_etl[mask].copy()


def build_pivot_q1(df_etl: pd.DataFrame) -> pd.DataFrame:
    """Pivot: SDO × cycle, filter hanya SDO di list insentif (semua channel)."""
    print("[3/6] Building pivot Q1 (filter SDO list, SALES+RETUR)...")

    filtered = _filter_sdo_insentif(df_etl)
    print(f"   filtered rows: {len(filtered):,}")

    pivot = filtered.pivot_table(
        index="SDO",
        columns="CYCLE",
        values="NET VALUE2",
        aggfunc="sum",
        fill_value=0,
    )

    # Pastikan kolom Q1 ada
    for c in Q1_CYCLES:
        if c not in pivot.columns:
            pivot[c] = 0
    pivot = pivot[Q1_CYCLES]

    # Pastikan semua SDO di list muncul walaupun 0
    pivot = pivot.reindex([s.upper().strip() for s in SDO_INSENTIF_LIST], fill_value=0)

    pivot["Total_Q1"] = pivot[Q1_CYCLES].sum(axis=1)
    pivot = pivot.reset_index()
    print(f"   pivot rows: {len(pivot)}")
    return pivot


def _tier_pct(ach_pct: float) -> str:
    """Label tier per cycle: 0.25% / 0.5% / 0.75% / -"""
    if ach_pct < TIER_CYCLE_THRESH[0] * 100:
        return "< 80%"
    if ach_pct < TIER_CYCLE_THRESH[1] * 100:
        return "0.25%"
    if ach_pct <= TIER_CYCLE_THRESH[2] * 100:
        return "0.50%"
    return "0.75%"


def _nilai_per_cycle(tier: str, target: float, ach: float) -> float:
    """Nilai insentif per cycle sesuai scheme:
       0.25% -> ach * 0.25%
       0.5%  -> target * 0.25% + (ach - target) * 0.5%
       0.75% -> target * 0.25% + (ach - target) * 0.75%
       <80%  -> 0
    """
    if tier == "0.25%":
        return ach * TIER_CYCLE_PCT[0]
    if tier == "0.50%":
        return target * TIER_CYCLE_PCT[0] + max(ach - target, 0) * TIER_CYCLE_PCT[1]
    if tier == "0.75%":
        return target * TIER_CYCLE_PCT[0] + max(ach - target, 0) * TIER_CYCLE_PCT[2]
    return 0.0


def _tier_quarterly(ach_ratio: float) -> tuple[str, float]:
    """VLOOKUP add-on quarterly: return (label, nilai_add) dari TIER_QUARTERLY."""
    # TIER_QUARTERLY sorted ascending by threshold
    for thresh, val in reversed(TIER_QUARTERLY):
        if ach_ratio >= thresh:
            return (f"{val*100:.2f}%", val)
    return ("0.00%", 0.0)


def _nilai_quarterly(ach_q1: float, target_q1: float) -> tuple[float, str, float]:
    """Insentif quarterly (ADD):
       ach_ratio = ach_q1 / target_q1
       if ach_ratio < 0.90 -> 0
       else -> (target_q1 * 0.10%) + (ach_q1 - target_q1) * tier_value
    """
    if target_q1 <= 0:
        return (0.0, "0.00%", 0.0)
    ach_ratio = ach_q1 / target_q1
    label, val = _tier_quarterly(ach_ratio)
    if ach_ratio < TIER_QUARTERLY[1][0]:  # < 0.90
        return (0.0, label, ach_ratio)
    if ach_ratio < 1.00:
        return (ach_q1 * val, label, ach_ratio)
    # ach_ratio >= 1.00
    return (target_q1 * 0.001 + max(ach_q1 - target_q1, 0) * val, label, ach_ratio)


def hitung_insentif_q1(pivot: pd.DataFrame, target_df: pd.DataFrame) -> pd.DataFrame:
    """Hitung insentif Q1 per SDO:
       - per cycle (3 kolom cycle)
       - quarterly add-on
       - total
    """
    print("[4/6] Menghitung insentif Q1 (per cycle + quarterly)...")

    pivot = pivot.copy()
    target_df = target_df.copy()
    pivot["SDO"] = pivot["SDO"].astype(str).str.strip().str.upper()
    target_df["SDO"] = target_df["SDO"].astype(str).str.strip().str.upper()

    # Pastikan urutan SDO sesuai SDO_INSENTIF_LIST
    pivot = pivot.set_index("SDO")
    sdo_order = [s.upper().strip() for s in SDO_INSENTIF_LIST]
    pivot = pivot.reindex(sdo_order, fill_value=0).reset_index()

    # Merge target
    target_q1 = target_df[["SDO", "C01", "C02", "C03"]].copy()
    target_q1.columns = ["SDO", "Tgt_C01", "Tgt_C02", "Tgt_C03"]
    merged = pivot.merge(target_q1, on="SDO", how="left").fillna(0)

    # Hitung per cycle
    for i, cyc in enumerate(Q1_CYCLES):
        tgt_col = f"Tgt_{Q1_CYCLE_NUM[i]}"
        ach_col = cyc
        pct_col = f"ACH%_{Q1_CYCLE_NUM[i]}"
        tier_col = f"Tier_{Q1_CYCLE_NUM[i]}"
        nilai_col = f"Nilai_{Q1_CYCLE_NUM[i]}"

        merged[pct_col] = merged.apply(
            lambda r: (r[ach_col] / r[tgt_col] * 100) if r[tgt_col] > 0 else 0.0,
            axis=1,
        )
        merged[tier_col] = merged[pct_col].apply(_tier_pct)
        merged[nilai_col] = merged.apply(
            lambda r: _nilai_per_cycle(r[tier_col], r[tgt_col], r[ach_col]),
            axis=1,
        )

    # Total & ACH% Q1
    merged["Target_Q1"] = merged[["Tgt_C01", "Tgt_C02", "Tgt_C03"]].sum(axis=1)
    merged["Ach_Q1"] = merged["Total_Q1"]
    merged["ACH_pct"] = merged.apply(
        lambda r: (r["Ach_Q1"] / r["Target_Q1"] * 100) if r["Target_Q1"] > 0 else 0.0,
        axis=1,
    )

    # Insentif quarterly (ADD)
    q_results = merged.apply(
        lambda r: _nilai_quarterly(r["Ach_Q1"], r["Target_Q1"]),
        axis=1,
    )
    merged["Tier_Quarterly"] = [q[1] for q in q_results]
    merged["Add_Quarterly"] = [q[0] for q in q_results]
    merged["ACH_ratio"] = [q[2] for q in q_results]

    # Total insentif = jumlah 3 cycle + ADD quarterly
    merged["Total_Insentif"] = (
        merged["Nilai_C01"] + merged["Nilai_C02"] + merged["Nilai_C03"] + merged["Add_Quarterly"]
    )

    # Tier ringkasan Q1 (berdasarkan ACH_pct Q1)
    merged["Tier"] = merged["ACH_pct"].apply(_tier_pct)

    # Susun kolom output
    out_cols = [
        "SDO",
        "C0126", "C0226", "C0326", "Total_Q1",
        "Tgt_C01", "Tgt_C02", "Tgt_C03", "Target_Q1",
        "ACH%_C01", "Tier_C01", "Nilai_C01",
        "ACH%_C02", "Tier_C02", "Nilai_C02",
        "ACH%_C03", "Tier_C03", "Nilai_C03",
        "ACH_pct", "Tier",
        "Tier_Quarterly", "Add_Quarterly",
        "Total_Insentif",
    ]
    merged = merged[out_cols].sort_values("ACH_pct", ascending=False).reset_index(drop=True)
    return merged


