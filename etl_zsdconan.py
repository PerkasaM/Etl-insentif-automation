def save_outputs(df_etl: pd.DataFrame, insentif: pd.DataFrame, pivot: pd.DataFrame) -> None:
    """Simpan file output ke folder output/."""
    print("[5/6] Saving outputs...")

    pgi_min = pd.to_datetime(df_etl["ACTUAL PGI DATE"], errors="coerce").min()
    pgi_max = pd.to_datetime(df_etl["ACTUAL PGI DATE"], errors="coerce").max()
    periode = f"{pgi_min.strftime('%Y%m%d')}_{pgi_max.strftime('%Y%m%d')}"

    # 1) ETL lengkap
    f1 = OUT_DIR / f"ZSDCONUN_ETL_{periode}.xlsx"
    with pd.ExcelWriter(f1, engine="openpyxl") as w:
        df_etl.to_excel(w, sheet_name="ZSDCONUN", index=False)
    print(f"   -> {f1.name}")

    # 2) Insentif Q1 + pivot
    f2 = OUT_DIR / f"Insentif_Q1_{periode[:4]}.xlsx"
    with pd.ExcelWriter(f2, engine="openpyxl") as w:
        pivot.to_excel(w, sheet_name="Achievement", index=False)
        insentif.to_excel(w, sheet_name="Insentif", index=False)
    print(f"   -> {f2.name}")


