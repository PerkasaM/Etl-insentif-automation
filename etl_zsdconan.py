def main() -> None:
    print("=" * 70)
    print("ETL INSENTIF - ZSDCONUN -> Insentif Q1")
    print("=" * 70)

    data = load_data()
    df_etl = transform(data)
    pivot = build_pivot_q1(df_etl)

    target = _get_target_quarters(data["target"])
    insentif = hitung_insentif_q1(pivot, target)

    save_outputs(df_etl, insentif, pivot)

    print()
    print("[6/6] HASIL INSENTIF Q1")
    print()
    show_cols = [
        "SDO", "Total_Q1", "Target_Q1", "ACH_pct", "Tier",
        "Nilai_C01", "Nilai_C02", "Nilai_C03", "Add_Quarterly", "Total_Insentif",
    ]
    print(insentif[show_cols].to_string(index=False))
    print()
    print(f"Total nilai insentif Q1: Rp {insentif['Total_Insentif'].sum():,.0f}")
    print("=" * 70)
    print("DONE.")


if __name__ == "__main__":
    main()
